import { open } from './cdp.mjs';
const t = await open({ out: process.argv[2], port: 9355, url: 'http://127.0.0.1:5173/?fullres', width: 1280, height: 720, dsf: 1 });
const { evaluate, shot, check, sleep, press, G, U, uiTexts } = t;
await evaluate(`(() => { const s = ${G}; s.traits = { hard: 0, calm: 0, rage: 2 }; s.lastTrait = 'rage'; s.endTutorial('absorbed'); s.spawnTimer = 1e9; s.fireCooldown = 1e9; return true; })()`); await sleep(700);
const b = await evaluate(`({ x: Math.round(${U}.ability.x), y: Math.round(${U}.ability.y), vis: ${U}.ability.visible, w: Math.round(${U}.w) })`);
check('desktop: the power sits top left, under the health bar', b.vis && b.x < 80 && b.y > 60 && b.y < 140, b);
const marks = await evaluate(`(() => { const u = ${U}; const key = u.ability.list.find(o => o.type === 'Text'); return { key: key?.text, keyShown: !!key?.visible, name: u.abilityCaption.text, nameShown: u.abilityCaption.visible, nameX: Math.round(u.abilityCaption.x) }; })()`);
check('the button always shows its key, and the power is named beside it (labels off)', marks.key === 'e' && marks.keyShown && marks.name === 'burst' && marks.nameShown && marks.nameX > 60, marks);
await sleep(3600);
check('a while later, the key and the name stay', (await uiTexts()).includes('burst'), await uiTexts());
await shot('desktop-power.png');
await press('e', 'KeyE', 69); await sleep(150);
check('E uses the power', (await evaluate(`${G}.abilityCooldown`)) > 5, await evaluate(`${G}.abilityCooldown`));
// Leaving fullscreen pauses. (Headless Chrome can't enter fullscreen, so the browser's own event is replayed.)
check('playing, not paused', !(await evaluate(`${G}.paused`)));
await evaluate(`document.dispatchEvent(new Event('fullscreenchange'))`); await sleep(400);
check('leaving fullscreen pauses at once', await evaluate(`${G}.paused`));
const fs = await evaluate(`(() => { const u = ${U}; return u.fsBtn ? { vis: u.fsBtn.visible, alpha: u.fsBtn.alpha, above: u.fsBtn.depth > u.menu.depth } : null; })()`);
check('the fullscreen button stays, lit and clickable, on the pause menu', fs && fs.vis && fs.alpha === 1 && fs.above, fs);
await shot('pause-fullscreen.png');
await sleep(3800);
check('and it does not fade while the menu is open', (await evaluate(`${U}.fsBtn.alpha`)) === 1);
await evaluate(`${G}.resumeGame()`); await sleep(300);
check('back in play it drops below menus again', (await evaluate(`${U}.fsBtn.depth`)) === 150);
await press(' ', 'Space', 32); await sleep(300);
check('space pauses', await evaluate(`${G}.paused`));
await press(' ', 'Space', 32); await sleep(300);
check('space resumes', !(await evaluate(`${G}.paused`)));
t.done();
